r"""build_package.py - builds the Thunderstore package "TF2_AI_Enhancements" (Titanfall 2 / Northstar) deterministically.

usage:
  python build_package.py [--version 1.0.0] [--team NAME] [--website-url URL] [--build-plugin] [--out DIR]
                          [--allow-version-mismatch] [--no-validate]
                          [--menu-dir DIR] [--sr-addon FILE] [--bridge-addon FILE] [--fg-addon FILE] [--plugin-dll FILE]
                          [--nvngx-dlss FILE]

FINAL packaging (the packaging stage) passes every input explicitly, so the zip is built from the final, tested builds
and never from whatever happens to sit in a build folder at that moment:
  python build_package.py --menu-dir C:\dev\tf2-nr-bridge\northstar_mod\TF2NR.GraphicsToggles
      --sr-addon <final tf2-dlss-sr.addon64> --bridge-addon <final tf2-nr-bridge.addon64>
      --fg-addon <final tf2-fg.addon64> --plugin-dll C:\dev\tf2-ai-mod\plugin\TF2AIEnhancements.dll
An input left out falls back to the default build output below; BUILD_INFO.json lists which inputs were explicit.
Test builds: --out test\pkg (never dist\, which is reserved for the final package).
Deterministic: the same input bytes give a byte-identical zip (sorted entries, fixed timestamp 2026-09-29 00:00:00,
fixed attributes, deflate level 9, generated files built from constants). Verified by building twice and comparing.

What it collects by default (the CURRENT build outputs, never the game folder):
  plugin      C:\dev\tf2-ai-mod\plugin\TF2AIEnhancements.dll            (--build-plugin runs plugin\build.bat first)
  add-ons     C:\dev\tf2-nr-bridge\sr_next\tf2-dlss-sr.addon64          (build: cmd //c ...\sr_next\build.bat)
              C:\dev\tf2-nr-bridge\bridge\tf2-nr-bridge.addon64         (build: cmd //c ...\bridge\build.bat)
              C:\dev\tf2-nr-bridge\fg\tf2-fg.addon64                    (build: cmd //c ...\fg\build.bat)
  vendored    vendor\ReShade64.dll   (ReShade 6.8.0.2155 add-on build, sha256 pinned in vendor\VENDOR.json)
              vendor\nvngx_dlss.dll  (NVIDIA DLSS SR runtime 310.9.1.0 from the official NVIDIA/DLSS v310.9.1 release,
                                      sha256 pinned in vendor\VENDOR.json, Authenticode NVIDIA)
  menu mod    C:\dev\tf2-nr-bridge\northstar_mod\TF2NR.GraphicsToggles (linted like deploy_mod.py; Version must equal
              the package version unless --allow-version-mismatch)
  static      package_files\README.md, CHANGELOG.md, THIRD_PARTY_NOTICES.txt, ReShade.ini, licenses\*, icon.png
              (icon.png is regenerated by tools\make_icon.py when missing)

Package tree (zip root = package root, as Thunderstore and r2modman/Viper expect; they install it unchanged to
R2Northstar\packages\<Team>-TF2_AI_Enhancements-<ver>\, where Northstar loads mods\*\mod.json and plugins\*.dll
non-recursively and adds plugins\lib to the DLL search path):
  manifest.json  icon.png  README.md  CHANGELOG.md  THIRD_PARTY_NOTICES.txt  licenses\...
  mods\TF2NR.GraphicsToggles\...
  plugins\TF2AIEnhancements.dll
  plugins\lib\ReShade64.dll  ReShade.ini  tf2-dlss-sr.addon64  tf2-nr-bridge.addon64  tf2-fg.addon64  nvngx_dlss.dll
             DLSS5_OPTIONAL_FILES.txt
  plugins\lib\proxy\dxgi.dll   (the same ReShade binary; the plugin loads it as dxgi.dll = proxy mode. It sits in a
                              sub-folder so Northstar's AddDllDirectory(plugins\lib) never offers it to a by-name load)
NOT included on purpose (THIRD_PARTY_NOTICES.txt): renodx-dlss5.addon64, nvngx_dlssnr.dll, DLSS5-Feeder, any log / csv
/ screenshot / probe / backup / Verify-*.ps1 file.

Outputs (in --out, default dist\):
  stage\                                   the unpacked package tree
  <Team>-TF2_AI_Enhancements-<ver>.zip     the upload zip (sorted entries, fixed timestamps + attributes, deflate 9:
                                           the same inputs give a byte-identical zip)
  BUILD_INFO.json                          source path, sha256, size and embedded version of every packaged file
  SHA256SUMS.txt                           sha256 of the zip and of every packaged file
Then validate_package.py runs on the zip (exit code 1 on any error).
"""
